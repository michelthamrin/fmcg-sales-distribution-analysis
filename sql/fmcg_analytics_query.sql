)

-- added non-selling percentage to the CTE
SELECT *,
    ROUND((non_selling_visits * 100.0) / total_visits, 2) AS non_selling_percentage
FROM outlet_performance
WHERE total_visits >= 5 
  AND ROUND((non_selling_visits * 100.0) / total_visits, 2) > 50.00
ORDER BY 
    non_selling_visits DESC,
    non_selling_percentage DESC;
    
/* 
====================================================================================
Outlet ABC Segmentation (Revenue Percentile Ranking)
Description:   Calculates the lifetime revenue for every outlet, ranks them, and 
               assigns an A, B, or C category based on their percentile standing 
               within the total outlet base. 
====================================================================================
*/

-- Calculate the lifetime revenue and total visits for every outlet
WITH outlet_revenue AS (
    SELECT 
        o.outlet_id,
        o.outlet_name,
        COUNT(DISTINCT v.visit_id) AS total_visits,
        SUM(vds.sales_value) AS total_revenue
    FROM outlets o
    JOIN visits v 
        ON o.outlet_id = v.outlet_id
    JOIN visit_details_with_sales_value vds 
        ON v.visit_id = vds.visit_id
    GROUP BY 
        o.outlet_id,
        o.outlet_name
),

-- Added percentile ranking to support grouping the outlets
abc_ranking AS (
    SELECT *,
        PERCENT_RANK() OVER (ORDER BY total_revenue DESC) AS revenue_percentile
    FROM outlet_revenue
    WHERE 
        total_revenue > 0
)

-- Assign the A/B/C labels based on the percentile
SELECT 
    outlet_id,
    outlet_name,
    total_visits,
    total_revenue,
    CASE 
        WHEN revenue_percentile <= 0.20 THEN 'A-Class (Top 20%)'
        WHEN revenue_percentile <= 0.50 THEN 'B-Class (Middle 30%)'
        ELSE 'C-Class (Bottom 50%)' 
    END AS abc_category
FROM abc_ranking
ORDER BY 
    total_revenue DESC;
    
/* 
====================================================================================
Cash vs. Consignment Performance by Product (Current Format)
Description:   Calculates the volume and revenue split between cash and consignment 
               transactions for each product, strictly using data from August 2025 
               onward when the dual-pricing structure was introduced.
====================================================================================
*/

-- Aggregate volume and revenue by transaction type for each product
WITH product_sales_split AS (
    SELECT 
        p.product_id,
        p.product_name,

        SUM(CASE WHEN vds.transaction_type = 'Consign' THEN vds.sales_qty ELSE 0 END) AS consign_qty,
        SUM(CASE WHEN vds.transaction_type != 'Consign' THEN vds.sales_qty ELSE 0 END) AS cash_qty,
        
        SUM(CASE WHEN vds.transaction_type = 'Consign' THEN COALESCE(vds.transaction_value, 0) ELSE 0 END) AS consign_revenue,
        SUM(CASE WHEN vds.transaction_type != 'Consign' THEN COALESCE(vds.transaction_value, 0) ELSE 0 END) AS cash_revenue,
        
        SUM(COALESCE(vds.transaction_value, 0)) AS total_product_revenue
    FROM products p
    JOIN visit_details_with_sales_value vds 
        ON p.product_id = vds.product_id
    JOIN visits v 
        ON vds.visit_id = v.visit_id
    WHERE 
        v.visit_date >= '2025-08-01'
        AND vds.sales_qty > 0
    GROUP BY 
        p.product_id,
        p.product_name
)

-- Added cash revenue percentage calculation to the CTE
SELECT *,    
    ROUND(
        (cash_revenue * 100.0) / NULLIF(total_product_revenue, 0), 
    2) AS cash_revenue_percentage
FROM product_sales_split
ORDER BY 
    cash_revenue_percentage DESC, 
    total_product_revenue DESC;
