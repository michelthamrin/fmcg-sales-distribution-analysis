USE sales_etl;

/*
====================================================================================
Create a consistent sales metric (sales_value) to compensate for the lack of 
transaction_value data on older records.
The metric was validated by combining recorded transaction_value with reconstructed 
legacy sales for empty rows.
Legacy records do not contain transaction_value. Their sales value is reconstructed 
as sales_qty x legacy_price.
====================================================================================
*/

CREATE OR REPLACE VIEW visit_details_with_sales_value AS
SELECT
    vd.*,
    CASE
        WHEN vd.transaction_value = 0
             AND vd.sales_qty > 0
        THEN vd.sales_qty * p.legacy_price
        ELSE vd.transaction_value
    END AS sales_value
FROM visit_details AS vd
INNER JOIN products AS p
    ON vd.product_id = p.product_id;
    
/*
====================================================================================
Route Conversion Rate and Average Sales Value
Description:   Evaluate route efficiency by calculating the percentage of total
			   visits that resulted in at least one sold item and the average
               sales value of each completed transactions.
====================================================================================
*/

-- Aggregate total revenue generated by each individual visits
WITH selling_visit_summary AS (
    SELECT 
        visit_id,
        SUM(sales_value) AS total_visit_revenue
    FROM visit_details_with_sales_value
    GROUP BY 
        visit_id
	HAVING
		total_visit_revenue > 0
)

-- Calculate conversion rate and average sales value by route
SELECT 
    v.route,
    COUNT(v.visit_id) AS total_visits,
    COUNT(svs.visit_id) AS successful_visits,
    ROUND(
        (COUNT(svs.visit_id) * 100.0) / NULLIF(COUNT(v.visit_id), 0), 
    2) AS conversion_rate_percentage,
    ROUND(
        SUM(svs.total_visit_revenue) / NULLIF(COUNT(svs.visit_id), 0), 
    2) AS average_sales_value

FROM visits v
LEFT JOIN selling_visit_summary svs 
    ON v.visit_id = svs.visit_id
GROUP BY 
    v.route
ORDER BY 
    conversion_rate_percentage DESC;
  
/*
====================================================================================
Non-Selling Visits Overall Percentage
Description:   Assess the distribution of outlets that have >50% non-selling visit
			   ratio across the distribution network (classified as 
               "Chronic Offender"). Added filter for >= 5 total visits to exclude
               unestablished/new outlets.
====================================================================================
*/
  
-- Aggregate total revenue generated by each individual visits
WITH selling_visit_summary AS (
    SELECT 
        visit_id,
        SUM(sales_value) AS total_visit_revenue
    FROM visit_details_with_sales_value
    GROUP BY 
        visit_id
	HAVING
		total_visit_revenue > 0
),

-- Calculate the non-selling ratio for each individual outlet
outlet_performance AS (
    SELECT 
        v.outlet_id,
        COUNT(v.visit_id) AS total_visits,
        COUNT(
            CASE WHEN svs.total_visit_revenue = 0 OR svs.total_visit_revenue IS NULL 
            THEN v.visit_id END
        ) AS non_selling_visits
    FROM visits v
    LEFT JOIN selling_visit_summary svs 
        ON v.visit_id = svs.visit_id
    GROUP BY 
        v.outlet_id
)

/* 
Aggregate globally to find the percentage of the network that falls into 
the "Chronic Offender" group.
Added filter for total_visits >= 5 to exclude unestablished/new outlets.
*/
SELECT 
    COUNT(outlet_id) AS qualified_outlets,
    COUNT(
        CASE WHEN (non_selling_visits * 100.0 / total_visits) > 50.00 
        THEN outlet_id END
    ) AS chronic_offender_outlets,
    ROUND(
        COUNT(CASE WHEN (non_selling_visits * 100.0 / total_visits) > 50.00 THEN outlet_id END) * 100.0 
        / COUNT(outlet_id), 
    2) AS network_saturation_percentage
FROM outlet_performance
WHERE total_visits >= 5;

/*
====================================================================================
Non-Selling Visits By Route
====================================================================================
*/

WITH selling_visit_summary AS (
    SELECT 
        visit_id,
        SUM(sales_value) AS total_visit_revenue
    FROM visit_details_with_sales_value
    GROUP BY 
        visit_id
    HAVING
        total_visit_revenue > 0
),

outlet_performance AS (
    SELECT 
        v.route, 
        v.outlet_id,
        COUNT(v.visit_id) AS total_visits,
        COUNT(
            CASE WHEN svs.total_visit_revenue = 0 OR svs.total_visit_revenue IS NULL 
            THEN v.visit_id END
        ) AS non_selling_visits
    FROM visits v
    LEFT JOIN selling_visit_summary svs 
        ON v.visit_id = svs.visit_id
    GROUP BY 
        v.route,
        v.outlet_id
)

-- Create route-level view of Chronic Offender distribution
SELECT 
    route,
    COUNT(outlet_id) AS qualified_outlets,
    COUNT(
        CASE WHEN (non_selling_visits * 100.0 / total_visits) > 50.00 
        THEN outlet_id END
    ) AS chronic_offender_outlets,
    ROUND(
        COUNT(CASE WHEN (non_selling_visits * 100.0 / total_visits) > 50.00 THEN outlet_id END) * 100.0 
        / NULLIF(COUNT(outlet_id), 0),
    2) AS route_saturation_percentage
FROM outlet_performance
WHERE total_visits >= 5
GROUP BY 
    route
ORDER BY 
    route_saturation_percentage DESC;

/*
====================================================================================
Non-Selling Visits By Outlet
====================================================================================
*/

WITH selling_visit_summary AS (
    SELECT 
        visit_id,
        SUM(sales_value) AS total_visit_revenue
    FROM visit_details_with_sales_value
    GROUP BY 
        visit_id
	HAVING
		total_visit_revenue > 0
),

outlet_performance AS (
    SELECT 
        v.outlet_id,
        COUNT(v.visit_id) AS total_visits,
        COUNT(
            CASE WHEN svs.total_visit_revenue = 0 OR svs.total_visit_revenue IS NULL 
